class FakePicker implements ProfileImagePicker {
  /// What the next pick returns (`null` = cancelled).
  Uint8List? result;
  Object? error;
  final List<(PhotoSource, PhotoShape)> picks = [];

  @override
  Future<Uint8List?> pick(
    PhotoSource source, {
    required PhotoShape shape,
    String? cropTitle,
  }) async {
    picks.add((source, shape));
    if (error case final e?) throw e;
    return result;
  }
}
